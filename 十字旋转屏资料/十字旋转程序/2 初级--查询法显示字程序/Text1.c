/*****n（us）延时子程序*****/
void DelayUs(uint N)
{
    uint x ;
    for(x=0;x<=N;x++);
}
/*****主函数*****/
void main(void)
{
    uint i=0,j=0 ,k=0; 


    while(1)
    {
        if(KEY==0) //红外接收管 判断起始位
        {
            j++;            
            if(j>sizeof(zimo)) //根据显示的字数定义改数值672/16=42个字 显示完42个字后 重新开始
            {
                j=0 ;
				k^=1;	  //变量K控制哪一边LED发光。一边显示完所有字后换另外一边
            }            
            for(i=128+j;i>j;i--) //每转一圈  前进一列  这里定义一圈中同时显示128/16=8个字，
            {                    //在这个程序中如果此参数设置过大会造成头吃尾的后果，如果过少盲点又会太大           
              					 //所以比较麻烦 要根据电机速度来调整此参数

				if(k){
					P1=zimo[i*2]; //送数据低位显示
					P3=zimo[i*2+1];//送数据高位显示
				}
				else
				{
					P2=zimo[i*2]; //送数据低位显示
					P0=zimo[i*2+1];//送数据高位显示
				}

                DelayUs(20);	//延时让LED亮起来 每列延时的时间
				P3=0xFF;
				P1=0xFF;
				P0=0xff;
				P2=0xff;
             
            }
        }



    }
}
